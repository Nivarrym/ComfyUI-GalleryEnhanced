"""Server-side, disk cached WebP thumbnails.

The image grid requests ``/Gallery/thumbnail?path=...&w=...`` instead of the
full-resolution original.  Cache keys include the real path, mtime, size, width
and a format version, so replacing a file or changing the generator invalidates
without any manual bookkeeping.  Writes are atomic (temp file + ``os.replace``)
and generated bytes are cached on disk under
``folder_paths.get_user_directory()/gallery/thumbnails`` (temp dir fallback).
"""

from __future__ import annotations

import hashlib
import io
import os
import tempfile
import threading
import time
from typing import Dict, Optional, Tuple

from PIL import Image, ImageOps, UnidentifiedImageError

from . import gallery_perf

#: Bump when the generated output changes (quality, resizing, encoding).
FORMAT_VERSION = "1"

MIN_WIDTH = 64
MAX_WIDTH = 1024
DEFAULT_QUALITY = 82

SUPPORTED_IMAGE_EXTENSIONS = frozenset({".png", ".jpg", ".jpeg", ".webp", ".gif"})
CONTENT_TYPE = "image/webp"

_cache_dir_override: Optional[str] = None
_cache_dir_lock = threading.Lock()


class ThumbnailError(Exception):
    def __init__(self, message: str, status: int = 400) -> None:
        super().__init__(message)
        self.status = int(status)


def set_cache_dir(path: Optional[str]) -> None:
    """Override the thumbnail directory (tests / custom deployments)."""
    global _cache_dir_override
    with _cache_dir_lock:
        _cache_dir_override = os.path.abspath(path) if path else None


def get_cache_dir() -> str:
    with _cache_dir_lock:
        override = _cache_dir_override
    if override:
        return override

    env_override = os.environ.get("GALLERY_THUMBNAIL_DIR")
    if env_override:
        return os.path.abspath(env_override)

    try:
        import folder_paths  # ComfyUI; imported lazily so tests need no ComfyUI

        user_dir = folder_paths.get_user_directory()
        if user_dir:
            return os.path.join(user_dir, "gallery", "thumbnails")
    except Exception:
        pass

    return os.path.join(tempfile.gettempdir(), "comfyui-gallery-thumbnails")


# --- per-key lock registry -------------------------------------------------

class _KeyLock:
    __slots__ = ("lock", "refs")

    def __init__(self) -> None:
        self.lock = threading.Lock()
        self.refs = 0


_locks_guard = threading.Lock()
_key_locks: Dict[str, _KeyLock] = {}

# Cache files generated for each real asset path, used by invalidate().
_index_guard = threading.Lock()
_index: Dict[str, set] = {}


def _acquire_key_lock(key: str) -> _KeyLock:
    with _locks_guard:
        entry = _key_locks.get(key)
        if entry is None:
            entry = _KeyLock()
            _key_locks[key] = entry
        entry.refs += 1
        return entry


def _release_key_lock(key: str, entry: _KeyLock) -> None:
    with _locks_guard:
        entry.refs -= 1
        if entry.refs <= 0:
            _key_locks.pop(key, None)


def _remember(real_norm: str, cache_file: str) -> None:
    with _index_guard:
        _index.setdefault(real_norm, set()).add(cache_file)


def _walkthrough_remove(path: str) -> None:
    try:
        os.remove(path)
    except OSError:
        pass


def invalidate(full_path: str) -> None:
    """Delete all cached thumbnail files for one asset (any width)."""
    try:
        real_norm = os.path.normcase(os.path.realpath(full_path))
    except (OSError, ValueError):
        real_norm = os.path.normcase(os.path.abspath(full_path))
    with _index_guard:
        cache_files = _index.pop(real_norm, set())
    for cache_file in cache_files:
        _walkthrough_remove(cache_file)


def clear_all() -> None:
    """Delete every thumbnail this process has seen (best effort)."""
    with _index_guard:
        everything = [path for paths in _index.values() for path in paths]
        _index.clear()
    for cache_file in everything:
        _walkthrough_remove(cache_file)


def _validate_width(width: object) -> int:
    try:
        value = int(width)
    except (TypeError, ValueError):
        raise ThumbnailError("Invalid width", 400)
    if value < MIN_WIDTH or value > MAX_WIDTH:
        raise ThumbnailError(
            f"Invalid width: expected {MIN_WIDTH}..{MAX_WIDTH}", 400
        )
    return value


def _cache_key(real_path: str, stat_result: os.stat_result, width: int) -> str:
    mtime_ns = getattr(stat_result, "st_mtime_ns", int(stat_result.st_mtime * 1_000_000_000))
    raw = "|".join(
        (os.path.normcase(real_path), str(int(mtime_ns)), str(int(stat_result.st_size)),
         str(int(width)), FORMAT_VERSION)
    )
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


def _cache_file(key: str) -> str:
    cache_dir = get_cache_dir()
    return os.path.join(cache_dir, key[:2], key + ".webp")


def _generate(real_path: str, width: int) -> bytes:
    try:
        with Image.open(real_path) as opened:
            try:
                opened.seek(0)  # first frame of animated formats
            except EOFError:
                pass
            # Bake EXIF orientation into pixels before resizing.
            image = ImageOps.exif_transpose(opened)
            try:
                image.thumbnail((width, width), Image.Resampling.LANCZOS)
                if image.mode not in ("RGB", "RGBA"):
                    if "A" in image.getbands() or "transparency" in image.info:
                        image = image.convert("RGBA")
                    else:
                        image = image.convert("RGB")
                buffer = io.BytesIO()
                image.save(
                    buffer,
                    format="WEBP",
                    quality=DEFAULT_QUALITY,
                    method=4,
                )
                return buffer.getvalue()
            finally:
                if image is not opened:
                    image.close()
    except UnidentifiedImageError as exc:
        raise ThumbnailError("Unsupported or corrupt image", 415) from exc
    except Image.DecompressionBombError as exc:
        raise ThumbnailError("Image is too large to thumbnail", 415) from exc
    except (OSError, ValueError) as exc:
        # Decompression bombs / truncated files / unreadable data.
        raise ThumbnailError(f"Unable to generate thumbnail: {exc}", 415) from exc


def _write_atomic(cache_file: str, data: bytes) -> None:
    directory = os.path.dirname(cache_file)
    os.makedirs(directory, exist_ok=True)
    fd, temp_path = tempfile.mkstemp(dir=directory, prefix=".thumb-", suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temp_path, cache_file)
    except BaseException:
        _walkthrough_remove(temp_path)
        raise


def get_thumbnail(full_path: str, width: object) -> Tuple[bytes, str, bool]:
    """Return ``(webp_bytes, content_type, cache_hit)`` for an image asset.

    Raises :class:`ThumbnailError` with an HTTP status for invalid widths,
    unsupported media and missing files.
    """
    requested_width = _validate_width(width)

    if not isinstance(full_path, str) or not full_path:
        raise ThumbnailError("path is required", 400)
    real_path = os.path.realpath(full_path)
    extension = os.path.splitext(real_path)[1].lower()
    if extension not in SUPPORTED_IMAGE_EXTENSIONS:
        raise ThumbnailError("Only raster images support thumbnails", 415)
    if not os.path.isfile(real_path):
        raise ThumbnailError("File not found", 404)

    started = time.perf_counter()
    try:
        stat_result = os.stat(real_path)
    except OSError as exc:
        raise ThumbnailError(f"File not found: {exc}", 404) from exc

    key = _cache_key(real_path, stat_result, requested_width)
    cache_file = _cache_file(key)
    real_norm = os.path.normcase(real_path)

    def _read_cache() -> Optional[bytes]:
        try:
            if os.path.getsize(cache_file) <= 0:
                return None
            with open(cache_file, "rb") as handle:
                return handle.read()
        except OSError:
            return None

    cached_bytes = _read_cache()
    if cached_bytes is not None:
        _remember(real_norm, cache_file)
        gallery_perf.note_thumbnail(
            True, (time.perf_counter() - started) * 1000.0, requested_width, len(cached_bytes)
        )
        return cached_bytes, CONTENT_TYPE, True

    entry = _acquire_key_lock(key)
    try:
        with entry.lock:
            # Another thread may have generated it while we waited for the lock.
            cached_bytes = _read_cache()
            if cached_bytes is not None:
                _remember(real_norm, cache_file)
                gallery_perf.note_thumbnail(
                    True, (time.perf_counter() - started) * 1000.0,
                    requested_width, len(cached_bytes),
                )
                return cached_bytes, CONTENT_TYPE, True

            with gallery_perf.timer(
                "thumbnail", width=requested_width, file=os.path.basename(real_path)
            ) as extra:
                data = _generate(real_path, requested_width)
                _write_atomic(cache_file, data)
                extra["bytes"] = len(data)
            _remember(real_norm, cache_file)
            gallery_perf.note_thumbnail(
                False, (time.perf_counter() - started) * 1000.0, requested_width, len(data)
            )
            return data, CONTENT_TYPE, False
    finally:
        _release_key_lock(key, entry)


def cache_path(full_path: str, width: object) -> Optional[str]:
    """Return the cache file path for an asset/width (diagnostics/tests)."""
    try:
        real_path = os.path.realpath(full_path)
        stat_result = os.stat(real_path)
        requested_width = _validate_width(width)
    except (OSError, ThumbnailError):
        return None
    return _cache_file(_cache_key(real_path, stat_result, requested_width))
