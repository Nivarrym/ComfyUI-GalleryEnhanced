"""Load an image from ComfyUI's output directory (including subfolders).

Unlike the built-in ``Load Image`` node, which only lists files from the input
directory, this node exposes all image files generated by ComfyUI across past
sessions.
"""

from __future__ import annotations

import os
import re

IMAGE_EXTENSIONS = frozenset({
    ".png", ".jpg", ".jpeg", ".webp", ".gif", ".bmp", ".tif", ".tiff",
})

_ANNOTATION_RE = re.compile(r"\s*\[(input|output|temp)\]\s*$", re.IGNORECASE)


def _output_root() -> str:
    import folder_paths

    return os.path.realpath(folder_paths.get_output_directory())


def _root_for_value(image: str) -> str:
    import folder_paths

    match = _ANNOTATION_RE.search(str(image))
    kind = match.group(1).lower() if match else "output"
    if kind == "input":
        return os.path.realpath(folder_paths.get_input_directory())
    if kind == "temp":
        return os.path.realpath(folder_paths.get_temp_directory())
    return _output_root()


def _normalize_relative(path: str) -> str:
    # ComfyUI's frontend uses the "[output]" suffix to tell its image loader
    # and mask editor which folder a combo value belongs to.
    value = _ANNOTATION_RE.sub("", str(path))
    return value.replace("\\", "/").strip().lstrip("/")


def _iter_gallery_images() -> list[str]:
    root = _output_root()
    found: list[str] = []
    for base, dirs, files in os.walk(root):
        # Do not descend into hidden/transient folders.
        dirs[:] = [name for name in dirs if not name.startswith(".")]
        for filename in files:
            if os.path.splitext(filename)[1].lower() not in IMAGE_EXTENSIONS:
                continue
            full_path = os.path.join(base, filename)
            relative = os.path.relpath(full_path, root).replace(os.sep, "/")
            # The annotation is understood by ComfyUI's image/mask editor and
            # stripped again by _normalize_relative before loading.
            found.append(f"{relative} [output]")
    found.sort(key=str.casefold)
    return found


def _resolve_image_path(image: str) -> str:
    root = _root_for_value(image)
    relative = _normalize_relative(image)
    if not relative:
        raise ValueError("No gallery image selected")
    full_path = os.path.realpath(os.path.join(root, relative.replace("/", os.sep)))
    try:
        inside_root = os.path.commonpath([root, full_path]) == root
    except ValueError:
        inside_root = False
    if not inside_root:
        raise ValueError("Image path is outside the ComfyUI image directory")
    if not os.path.isfile(full_path):
        raise ValueError(f"Image not found: {relative}")
    if os.path.splitext(full_path)[1].lower() not in IMAGE_EXTENSIONS:
        raise ValueError(f"Unsupported image type: {relative}")
    return full_path


class LoadImageFromGallery:
    """Load an image generated by ComfyUI, including nested output folders."""

    @classmethod
    def INPUT_TYPES(cls):
        files = _iter_gallery_images()
        return {
            "required": {
                "image": (
                    files if files else [""],
                    {
                        "tooltip": (
                            "Images from the ComfyUI output directory and its "
                            "subfolders, including files from previous sessions."
                        ),
                    },
                ),
            },
        }

    RETURN_TYPES = ("IMAGE", "MASK")
    RETURN_NAMES = ("IMAGE", "MASK")
    FUNCTION = "load_image"
    CATEGORY = "image"
    DESCRIPTION = (
        "Load an image from the ComfyUI output directory or any of its "
        "subfolders. Unlike Load Image, it also sees files from old sessions."
    )
    SEARCH_ALIASES = [
        "load image", "gallery image", "output image", "previous session image",
    ]

    @classmethod
    def VALIDATE_INPUTS(cls, image):
        try:
            _resolve_image_path(image)
        except (OSError, ValueError) as error:
            return str(error)
        return True

    @classmethod
    def IS_CHANGED(cls, image):
        try:
            path = _resolve_image_path(image)
            stat = os.stat(path)
        except (OSError, ValueError):
            return float("NaN")
        return f"{getattr(stat, 'st_mtime_ns', int(stat.st_mtime * 1_000_000_000))}-{stat.st_size}"

    def load_image(self, image):
        import numpy as np
        import torch
        from PIL import Image, ImageOps, ImageSequence

        image_path = _resolve_image_path(image)

        output_images = []
        output_masks = []
        width = height = None

        with Image.open(image_path) as opened:
            for frame in ImageSequence.Iterator(opened):
                frame = ImageOps.exif_transpose(frame)
                rgb = frame.convert("RGB")
                if width is None:
                    width, height = rgb.size
                if rgb.size != (width, height):
                    continue

                array = np.asarray(rgb).astype(np.float32) / 255.0
                output_images.append(torch.from_numpy(array).unsqueeze(0))

                if "A" in frame.getbands():
                    alpha = np.asarray(frame.getchannel("A")).astype(np.float32) / 255.0
                    mask = 1.0 - torch.from_numpy(alpha)
                else:
                    mask = torch.zeros((64, 64), dtype=torch.float32)
                output_masks.append(mask.unsqueeze(0))

        if not output_images:
            raise ValueError(f"Image contains no usable frames: {image}")

        image_tensor = torch.cat(output_images, dim=0)
        mask_tensor = torch.cat(output_masks, dim=0)

        try:
            import comfy.model_management as model_management

            dtype = model_management.intermediate_dtype()
            device = model_management.intermediate_device()
            image_tensor = image_tensor.to(device=device, dtype=dtype)
            mask_tensor = mask_tensor.to(device=device, dtype=dtype)
        except Exception:
            # Loading still works on CPU if model management is unavailable.
            pass

        return (image_tensor, mask_tensor)


NODE_CLASS_MAPPINGS = {"LoadImageFromGallery": LoadImageFromGallery}
NODE_DISPLAY_NAME_MAPPINGS = {"LoadImageFromGallery": "Load Image From Gallery"}
